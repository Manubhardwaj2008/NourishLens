package com.example.nourishlens.ui.screens

import androidx.compose.foundation.Image
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.nourishlens.data.SampleData
import com.example.nourishlens.model.ProductScan
import com.example.nourishlens.ui.components.ComplianceStatusPill
import com.example.nourishlens.ui.theme.*

@Composable
fun CleanSwapsScreen(
    currentScan: ProductScan,
    onSelectSwapProduct: (ProductScan) -> Unit
) {
    val violations = currentScan.complianceResult.violations
    val compliantSwaps = remember {
        SampleData.createInitialScans().filter { it.complianceResult.isCompliant && it.id != currentScan.id }
    }

    var noticeGenerated by remember { mutableStateOf(false) }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(SurfaceWarmOat)
            .verticalScroll(rememberScrollState())
            .padding(horizontal = 16.dp, vertical = 12.dp)
    ) {
        // Section Title
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically
        ) {
            Row(
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                Icon(
                    imageVector = Icons.Default.Gavel,
                    contentDescription = null,
                    tint = ForestPrimary,
                    modifier = Modifier.size(20.dp)
                )
                Text(
                    text = "REMEDIATION & COMPLIANT SWAPS",
                    style = MaterialTheme.typography.labelSmall,
                    color = ForestPrimary,
                    fontWeight = FontWeight.Bold,
                    fontSize = 11.sp,
                    letterSpacing = 1.sp
                )
            }
        }

        Spacer(modifier = Modifier.height(12.dp))

        // Official Remediation Notice Generator Card
        Card(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(16.dp))
                .border(
                    1.dp,
                    if (violations.isNotEmpty()) NonComplianceRed.copy(alpha = 0.5f) else ForestPrimary.copy(alpha = 0.3f),
                    RoundedCornerShape(16.dp)
                ),
            colors = CardDefaults.cardColors(containerColor = CardMilledLinen)
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        Box(
                            modifier = Modifier
                                .size(32.dp)
                                .clip(RoundedCornerShape(8.dp))
                                .background(if (violations.isNotEmpty()) NonComplianceRedBg else HerbalMint),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = if (violations.isNotEmpty()) Icons.Default.Warning else Icons.Default.Verified,
                                contentDescription = null,
                                tint = if (violations.isNotEmpty()) NonComplianceRedText else ForestPrimary,
                                modifier = Modifier.size(18.dp)
                            )
                        }

                        Column {
                            Text(
                                text = "LEGAL REMEDIATION ADVISORY",
                                style = MaterialTheme.typography.labelSmall,
                                color = ForestPrimary,
                                fontWeight = FontWeight.Bold,
                                fontSize = 10.sp
                            )
                            Text(
                                text = currentScan.productName,
                                style = MaterialTheme.typography.titleMedium,
                                color = CharcoalEspresso,
                                fontWeight = FontWeight.Bold,
                                fontSize = 15.sp
                            )
                        }
                    }

                    ComplianceStatusPill(
                        isCompliant = currentScan.complianceResult.isCompliant,
                        score = currentScan.complianceResult.overallScore
                    )
                }

                Spacer(modifier = Modifier.height(12.dp))
                HorizontalDivider(color = OutlineHairline.copy(alpha = 0.3f))
                Spacer(modifier = Modifier.height(10.dp))

                if (violations.isNotEmpty()) {
                    Text(
                        text = "The following ${violations.size} regulatory violation(s) require seller rectification before distribution:",
                        style = MaterialTheme.typography.bodySmall,
                        color = CharcoalEspresso,
                        fontWeight = FontWeight.Medium
                    )

                    Spacer(modifier = Modifier.height(8.dp))

                    violations.forEach { violation ->
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 4.dp)
                                .background(NonComplianceRedBg.copy(alpha = 0.5f), RoundedCornerShape(8.dp))
                                .padding(10.dp),
                            horizontalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            Icon(
                                imageVector = Icons.Default.ErrorOutline,
                                contentDescription = null,
                                tint = NonComplianceRedText,
                                modifier = Modifier.size(16.dp)
                            )
                            Column {
                                Text(
                                    text = "${violation.ruleCode}: ${violation.ruleTitle}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = NonComplianceRedText,
                                    fontWeight = FontWeight.Bold
                                )
                                Text(
                                    text = "Action Required: ${violation.remediationGuidance}",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = CharcoalEspresso,
                                    fontSize = 11.sp
                                )
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(12.dp))

                    Button(
                        onClick = { noticeGenerated = !noticeGenerated },
                        modifier = Modifier.fillMaxWidth(),
                        colors = ButtonDefaults.buttonColors(
                            containerColor = if (noticeGenerated) ForestPrimary else NonComplianceRed
                        ),
                        shape = RoundedCornerShape(20.dp)
                    ) {
                        Icon(
                            imageVector = if (noticeGenerated) Icons.Default.CheckCircle else Icons.Default.Description,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(modifier = Modifier.width(6.dp))
                        Text(
                            text = if (noticeGenerated) "Advisory Notice Issued & Logged" else "Generate Official Seizure & Remediation Notice",
                            style = MaterialTheme.typography.labelMedium,
                            color = Color.White,
                            fontWeight = FontWeight.Bold
                        )
                    }
                } else {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        Icon(
                            imageVector = Icons.Default.CheckCircle,
                            contentDescription = null,
                            tint = ComplianceGreen,
                            modifier = Modifier.size(20.dp)
                        )
                        Text(
                            text = "No legal metrology violations detected for this item. Packaging meets all Rule 6 standards.",
                            style = MaterialTheme.typography.bodyMedium,
                            color = ForestPrimary,
                            fontWeight = FontWeight.Medium
                        )
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(18.dp))

        // Compliant Alternatives Catalogue Header
        Text(
            text = "FULLY COMPLIANT CERTIFIED ALTERNATIVES",
            style = MaterialTheme.typography.labelSmall,
            color = ForestPrimary,
            fontWeight = FontWeight.Bold,
            fontSize = 11.sp,
            letterSpacing = 1.sp
        )

        Spacer(modifier = Modifier.height(8.dp))

        Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
            compliantSwaps.forEach { swap ->
                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .clip(RoundedCornerShape(14.dp))
                        .border(1.dp, ForestPrimary.copy(alpha = 0.2f), RoundedCornerShape(14.dp)),
                    colors = CardDefaults.cardColors(containerColor = SurfaceContainerLow)
                ) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(12.dp),
                        horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Box(
                            modifier = Modifier
                                .size(60.dp)
                                .clip(RoundedCornerShape(10.dp))
                                .background(SurfaceContainerHighest),
                            contentAlignment = Alignment.Center
                        ) {
                            swap.imageResId?.let { resId ->
                                Image(
                                    painter = painterResource(id = resId),
                                    contentDescription = null,
                                    modifier = Modifier.fillMaxSize(),
                                    contentScale = ContentScale.Crop
                                )
                            }
                        }

                        Column(modifier = Modifier.weight(1f)) {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.spacedBy(4.dp)
                            ) {
                                Icon(
                                    imageVector = Icons.Default.Verified,
                                    contentDescription = null,
                                    tint = ComplianceGreen,
                                    modifier = Modifier.size(14.dp)
                                )
                                Text(
                                    text = "100% VERIFIED • ${swap.extractedFields.netQuantity}",
                                    style = MaterialTheme.typography.labelSmall,
                                    color = ForestPrimary,
                                    fontWeight = FontWeight.Bold,
                                    fontSize = 10.sp
                                )
                            }

                            Text(
                                text = swap.productName,
                                style = MaterialTheme.typography.titleMedium,
                                color = CharcoalEspresso,
                                fontWeight = FontWeight.Bold,
                                fontSize = 15.sp
                            )

                            Text(
                                text = "${swap.brandName} • ${swap.extractedFields.mrp}",
                                style = MaterialTheme.typography.bodySmall,
                                color = CharcoalVariant,
                                fontSize = 12.sp
                            )
                        }

                        Button(
                            onClick = { onSelectSwapProduct(swap) },
                            colors = ButtonDefaults.buttonColors(containerColor = ForestPrimary),
                            shape = RoundedCornerShape(16.dp),
                            contentPadding = PaddingValues(horizontal = 10.dp, vertical = 6.dp)
                        ) {
                            Text(
                                text = "Inspect",
                                style = MaterialTheme.typography.labelSmall,
                                color = Color.White,
                                fontSize = 11.sp
                            )
                        }
                    }
                }
            }
        }

        Spacer(modifier = Modifier.height(24.dp))
    }
}
